#include <stdio.h>
#include <string.h>

// Flag di-XOR dengan sebuah kunci 1-byte.
unsigned char enc[] = { 0x05, 0x07, 0x0f, 0x03, 0x11, 0x16, 0x0b, 0x09, 0x73, 0x7b, 0x39, 0x3a, 0x72, 0x30, 0x1d, 0x2b, 0x36, 0x1d, 0x20, 0x23, 0x21, 0x29, 0x1d, 0x76, 0x25, 0x23, 0x2b, 0x2c, 0x3f };
int n = 29;

int main() {
    char dec[128];
    for (int i = 0; i < n; i++) dec[i] = enc[i] ^ 0x42;
    dec[n] = 0;
    printf(dec);
}
